"""Analysis for H0-H4 and the moderators, per subject model. Reads data/{claims,runs,labels_judge}.jsonl.

    python src/analyze.py

Writes results/summary.md (tables), results/results.json, results/survival.{pdf,png}.
Decisions (fixed before looking at results, 2026-11-16):
- Ownership rate = share of replies labelled owns (unclear / parse failures dropped from the denominator,
  counts reported). S1 uses sample 0 of both paraphrases.
- A chain = S1 p0 -> S2 -> S3..S5 at one blatancy. Leaving Defends = first step whose label is not Defends
  (silent+endorses counts as Defends). Chains that hold to S5 are censored ("never").
- CIs: 95% percentile bootstrap over prompts (2,000 resamples). Kappa: Cohen's, with raw agreement.
"""
import json, random
from collections import Counter, defaultdict
import numpy as np
from sklearn.metrics import cohen_kappa_score
from common import CLAIMS, LABELS, RUNS, ROOT, SUBJECTS, read_jsonl

OUT = ROOT / "results"
TYPES = ("stated", "implied", "foil")
random.seed(0)


def boot(rows_by_prompt, stat, n=2000):
    """rows_by_prompt: {prompt_id: [items]}; stat(list of items) -> float. Returns (point, lo, hi)."""
    pids = list(rows_by_prompt)
    flat = [x for p in pids for x in rows_by_prompt[p]]
    point = stat(flat)
    vals = []
    for _ in range(n):
        s = [x for p in random.choices(pids, k=len(pids)) for x in rows_by_prompt[p]]
        v = stat(s)
        if v is not None and not np.isnan(v):
            vals.append(v)
    if point is None or not vals:
        return (point, None, None)
    return (point, float(np.percentile(vals, 2.5)), float(np.percentile(vals, 97.5)))


def fmt(t, pct=True):
    p, lo, hi = t
    if p is None or (isinstance(p, float) and np.isnan(p)):
        return "n/a"
    f = (lambda v: f"{100 * v:.0f}%") if pct else (lambda v: f"{v:.2f}")
    return f"{f(p)} [{f(lo)}, {f(hi)}]" if lo is not None else f(p)


def rate(items, key, val):
    xs = [x for x in items if x.get(key) not in (None, "unclear")]
    return sum(x[key] == val for x in xs) / len(xs) if xs else None


def by_prompt(items):
    d = defaultdict(list)
    for x in items:
        d[x["prompt_id"]].append(x)
    return d


def kappa(pairs):
    pairs = [(a, b) for a, b in pairs if a and b]
    if not pairs:
        return None, None, 0
    a, b = zip(*pairs)
    raw = sum(x == y for x, y in pairs) / len(pairs)
    k = cohen_kappa_score(a, b) if len(set(a) | set(b)) > 1 else float("nan")
    return k, raw, len(pairs)


def main():
    OUT.mkdir(exist_ok=True)
    claims = {c["claim_id"]: c for c in read_jsonl(CLAIMS)}
    labels = {(l["claim_id"], l["branch"], l["step"], l["sample_idx"]): l
              for l in read_jsonl(LABELS) if l.get("parse_ok")}
    nfail = sum(not l.get("parse_ok") for l in read_jsonl(LABELS))
    runs = [r for r in read_jsonl(RUNS) if r["step"] >= 1]
    items = []
    for r in runs:
        l = labels.get((r["claim_id"], r["branch"], r["step"], r["sample_idx"]))
        if l:
            c = claims[r["claim_id"]]
            items.append({**{k: c[k] for k in ("claim_id", "prompt_id", "model", "topic", "criticality",
                                                "claim_type", "strength", "x_true")},
                          **{k: r[k] for k in ("branch", "step", "sample_idx", "blatancy")},
                          **{k: l[k] for k in ("ownership", "stance", "label", "flags_evidence", "silent_endorse")}})
    res, md = {}, ["# Results (auto-generated by src/analyze.py; do not edit)\n",
                   f"Judge parse failures dropped: {nfail}\n"]
    models = [m for m in SUBJECTS if any(x["model"] == m for x in items)]
    fig_data = {}
    for m in models:
        R = res[m] = {}
        it = [x for x in items if x["model"] == m]
        cl = [c for c in claims.values() if c["model"] == m]
        md += [f"\n## {m}\n",
               f"Prompts: {len({c['prompt_id'] for c in cl})}; judged replies: {len(it)}; "
               f"x_true (stated+implied): {dict(Counter(c['x_true'] for c in cl if c['claim_type'] != 'foil'))}; "
               f"implied strength: {dict(sorted(Counter(c['strength'] for c in cl if c['claim_type'] == 'implied').items()))}\n"]
        idx = {(x["claim_id"], x["branch"], x["step"], x["sample_idx"]): x for x in it}

        # ---- H0: stability and ordering at S1
        s1 = [x for x in it if x["step"] == 1 and x["sample_idx"] == 0]
        para = [(idx.get((c, "s1_p0", 1, 0), {}).get("ownership"), idx.get((c, "s1_p1", 1, 0), {}).get("ownership"))
                for c in {x["claim_id"] for x in s1}]
        rep = [(x["ownership"], idx.get((x["claim_id"], x["branch"], 1, 1), {}).get("ownership"))
               for x in s1 if (x["claim_id"], x["branch"], 1, 1) in idx]
        para_l = [(idx.get((c, "s1_p0", 1, 0), {}).get("label"), idx.get((c, "s1_p1", 1, 0), {}).get("label"))
                  for c in {x["claim_id"] for x in s1}]
        kp, kr, kl = kappa(para), kappa(rep), kappa(para_l)
        R["h0"] = {"kappa_paraphrase_ownership": kp, "kappa_repeat_ownership": kr, "kappa_paraphrase_label": kl}
        own = {t: boot(by_prompt([x for x in s1 if x["claim_type"] == t]), lambda s: rate(s, "ownership", "owns"))
               for t in TYPES}
        R["h0"]["owns_s1"] = own
        md += ["\n### H0 (gate) and H1: S1\n",
               f"- ownership kappa, paraphrase p0 vs p1: {kp[0]:.2f} (raw {kp[1]:.0%}, n={kp[2]})" if kp[1] is not None else "- paraphrase kappa: n/a",
               f"- ownership kappa, repeat (k0 t=0 vs k1 t=0.7, pilot prompts): {kr[0]:.2f} (raw {kr[1]:.0%}, n={kr[2]})" if kr[1] is not None else "- repeat kappa: n/a",
               f"- label kappa, paraphrase: {kl[0]:.2f} (raw {kl[1]:.0%}, n={kl[2]})" if kl[1] is not None else "",
               "\n| claim type | n | owns | disowns | silent | unclear | owns rate [95% CI] |", "|---|---|---|---|---|---|---|"]
        for t in TYPES:
            xs = [x for x in s1 if x["claim_type"] == t]
            cnt = Counter(x["ownership"] for x in xs)
            md.append(f"| {t} | {len(xs)} | {cnt['owns']} | {cnt['disowns']} | {cnt['silent']} | {cnt['unclear']} | {fmt(own[t])} |")
        gap = boot(by_prompt([x for x in s1 if x["claim_type"] in ("stated", "implied")]),
                   lambda s: (rate([x for x in s if x["claim_type"] == "stated"], "ownership", "owns") or 0)
                   - (rate([x for x in s if x["claim_type"] == "implied"], "ownership", "owns") or 0))
        R["h1_gap"] = gap
        md.append(f"\nH1 gap (stated − implied owns rate at S1): {fmt(gap)}")
        # implied − foil (gap above the false-ownership floor); own RNG state so the CIs
        # computed after this point are unchanged from earlier runs
        _st = random.getstate()
        random.seed(f"foilgap|{m}")
        fgap = boot(by_prompt([x for x in s1 if x["claim_type"] in ("implied", "foil")]),
                    lambda s: (rate([x for x in s if x["claim_type"] == "implied"], "ownership", "owns") or 0)
                    - (rate([x for x in s if x["claim_type"] == "foil"], "ownership", "owns") or 0))
        random.setstate(_st)
        R["h1_gap_implied_foil"] = fgap
        md.append(f"Gap implied − foil (owns rate at S1): {fmt(fgap)}")
        imp = [x for x in s1 if x["claim_type"] == "implied"]
        md.append("Implied owns rate by strength: " + ", ".join(
            f"{s}: {rate([x for x in imp if x['strength'] == s], 'ownership', 'owns'):.0%} (n={sum(x['strength'] == s for x in imp)})"
            for s in sorted({x["strength"] for x in imp})))

        # ---- chains: H2, H3, H4, moderators
        chains = []
        for c in cl:
            if c["claim_type"] == "foil":
                continue
            for b in (1, 2, 3):
                seq = [idx.get((c["claim_id"], "s1_p0", 1, 0)), idx.get((c["claim_id"], "s2", 2, 0))] + \
                      [idx.get((c["claim_id"], f"chain_b{b}", s, 0)) for s in (3, 4, 5)]
                if any(s is None for s in seq):
                    continue
                first = next((i + 1 for i, s in enumerate(seq) if s["label"] != "Defends"), None)
                mode = None
                if first:
                    s = seq[first - 1]
                    mode = ("Denies (disowns)" if s["ownership"] == "disowns" else
                            "Denies (silent reversal)" if s["label"] == "Denies" else s["label"])
                chains.append({"prompt_id": c["prompt_id"], "claim_type": c["claim_type"], "blatancy": b,
                               "criticality": c["criticality"], "topic": c["topic"], "first": first, "mode": mode,
                               "flags": [s["flags_evidence"] for s in seq[2:]], "labels": [s["label"] for s in seq]})
        R["n_chains"] = len(chains)
        md += [f"\n### H2: when it leaves Defends (chains: {len(chains)}; step 1 = S1 p0)\n",
               "| claim type | n chains | not Defending at S1 | S2 | S3 | S4 | S5 | holds to S5 | mean first step (never = 6) [CI] |",
               "|---|---|---|---|---|---|---|---|---|"]
        surv = {}
        for t in ("stated", "implied"):
            xs = [x for x in chains if x["claim_type"] == t]
            cnt = Counter(x["first"] for x in xs)
            mean = boot(by_prompt(xs), lambda s: float(np.mean([x["first"] or 6 for x in s])) if s else None)
            R[f"h2_{t}"] = {"first_counts": {str(k): v for k, v in cnt.items()}, "mean_first": mean}
            md.append(f"| {t} | {len(xs)} | " + " | ".join(str(cnt.get(s, 0)) for s in range(1, 6)) +
                      f" | {cnt.get(None, 0)} | {fmt(mean, pct=False)} |")
            n = len(xs)
            surv[t] = [1.0] + [sum(1 for x in xs if x["first"] is None or x["first"] > s) / n for s in range(1, 6)] if n else []
        fig_data[m] = surv
        # conditional on Defends at S1: share that leaves at S2 (each claim's 3 chains share S1-S2,
        # so this is per claim, weighted x3); own RNG state so later CIs are unchanged
        _st = random.getstate()
        random.seed(f"s2cond|{m}")
        held1 = [x for x in chains if x["first"] != 1]
        s2rate = lambda s: sum(x["first"] == 2 for x in s) / len(s) if s else None
        for t in ("stated", "implied"):
            R[f"h2_s2_given_s1_{t}"] = boot(by_prompt([x for x in held1 if x["claim_type"] == t]), s2rate)
        R["h2_s2_given_s1_diff"] = boot(by_prompt(held1), lambda s: (
            (s2rate([x for x in s if x["claim_type"] == "implied"]) or 0)
            - (s2rate([x for x in s if x["claim_type"] == "stated"]) or 0)))
        random.setstate(_st)
        md.append("Left at S2, of chains Defending at S1: " + ", ".join(
            f"{t} {fmt(R[f'h2_s2_given_s1_{t}'])}" for t in ("stated", "implied"))
            + f"; implied − stated {fmt(R['h2_s2_given_s1_diff'])}")
        md += ["\n### H3: how it leaves (label at the first non-Defends step)\n",
               "| claim type | Corrects | Softens | Denies (disowns) | Denies (silent reversal) | Unclear |", "|---|---|---|---|---|---|"]
        for t in ("stated", "implied"):
            cnt = Counter(x["mode"] for x in chains if x["claim_type"] == t and x["mode"])
            tot = sum(cnt.values()) or 1
            R[f"h3_{t}"] = dict(cnt)
            md.append(f"| {t} | " + " | ".join(f"{cnt[k]} ({cnt[k] / tot:.0%})" for k in
                                                 ("Corrects", "Softens", "Denies (disowns)", "Denies (silent reversal)", "Unclear")) + " |")
        md += ["\n### H4: blatancy (left Defends by S5; evidence questioned at S3–S5)\n",
               "| blatancy | stated: left by S5 [CI] | implied: left by S5 [CI] | flags evidence (S3–S5 replies) | left only at S3–S5 (held through S2) |",
               "|---|---|---|---|---|"]
        for b in (1, 2, 3):
            row = [str(b)]
            for t in ("stated", "implied"):
                xs = [x for x in chains if x["claim_type"] == t and x["blatancy"] == b]
                v = boot(by_prompt(xs), lambda s: sum(x["first"] is not None for x in s) / len(s) if s else None)
                R[f"h4_b{b}_{t}"] = v
                row.append(fmt(v))
            xs = [x for x in chains if x["blatancy"] == b]
            fl = [f for x in xs for f in x["flags"] if f != "na"]
            held = [x for x in xs if x["first"] is None or x["first"] >= 3]
            late = sum(x["first"] is not None for x in held)
            R[f"h4_b{b}_flags"] = sum(f == "yes" for f in fl) / len(fl) if fl else None
            # all judged S3-S5 replies (incl. chains with a missing label) that question the evidence:
            # share still labelled Defends
            fd = [x["label"] for x in it if x["branch"] == f"chain_b{b}" and x["flags_evidence"] == "yes"]
            R[f"h4_b{b}_flags_defends"] = sum(lab == "Defends" for lab in fd) / len(fd) if fd else None
            R[f"h4_b{b}_flags_defends_n"] = len(fd)
            row += [f"{sum(f == 'yes' for f in fl) / len(fl):.0%} (n={len(fl)})" if fl else "n/a",
                    f"{late}/{len(held)}" + (f" ({late / len(held):.0%})" if held else "")]
            md.append("| " + " | ".join(row) + " |")
        md.append("Of S3–S5 replies that question the evidence, share still Defending: " + ", ".join(
            f"b{b} {R[f'h4_b{b}_flags_defends']:.0%} (n={R[f'h4_b{b}_flags_defends_n']})"
            for b in (1, 2, 3) if R[f"h4_b{b}_flags_defends"] is not None))
        # H4 restricted to chains still Defending after S2 (the only chains the S3-S5 evidence can move;
        # added 2026-11-16 after the first look); own RNG state so earlier CIs are unchanged
        _st = random.getstate()
        random.seed(f"h4cond|{m}")
        md += ["\n### H4 among chains Defending after S2: left Defends at S3–S5\n",
               "| blatancy | stated [CI] (n) | implied [CI] (n) | pooled [CI] (n) |", "|---|---|---|---|"]
        left = lambda s: sum(x["first"] is not None for x in s) / len(s) if s else None
        for b in (1, 2, 3):
            row = [str(b)]
            for t in ("stated", "implied", "pooled"):
                xs = [x for x in chains if x["blatancy"] == b and (t == "pooled" or x["claim_type"] == t)
                      and (x["first"] is None or x["first"] >= 3)]
                v = boot(by_prompt(xs), left)
                R[f"h4c_b{b}_{t}"] = v
                R[f"h4c_b{b}_{t}_n"] = len(xs)
                row.append(f"{fmt(v)} ({len(xs)})")
            md.append("| " + " | ".join(row) + " |")
        held = [x for x in chains if x["first"] is None or x["first"] >= 3]
        for b in (1, 2):
            R[f"h4c_b3_minus_b{b}"] = boot(by_prompt(held), lambda s, b=b: (
                (left([x for x in s if x["blatancy"] == 3]) or 0) - (left([x for x in s if x["blatancy"] == b]) or 0)))
        random.setstate(_st)
        md.append("Pooled, blatant − plausible: " + fmt(R["h4c_b3_minus_b1"]) +
                  "; blatant − dubious: " + fmt(R["h4c_b3_minus_b2"]))
        md += ["\n### Moderators: left Defends by S5 (all blatancies)\n",
               "| group | stated | implied |", "|---|---|---|"]
        for key, vals in (("criticality", (1, 2, 3)), ("topic", ("health", "money", "relationships"))):
            for v in vals:
                cells = []
                for t in ("stated", "implied"):
                    xs = [x for x in chains if x["claim_type"] == t and x[key] == v]
                    p = boot(by_prompt(xs), lambda s: sum(x["first"] is not None for x in s) / len(s) if s else None)
                    R[f"mod_{key}_{v}_{t}"] = p
                    cells.append(fmt(p) + f" (n={len(xs)})")
                md.append(f"| {key} {v} | " + " | ".join(cells) + " |")
        # ---- criticality: how long each claim is defended (added 2026-11-16, after the first look; descriptive)
        md += ["\n### Criticality: defending by step (S1 owns uses p0 only, the chain start)\n",
               "| claim | criticality | prompts | owns at S1 [CI] | Defends after S2 [CI] | holds to S5 [CI] | mean first step (never = 6) [CI] |",
               "|---|---|---|---|---|---|---|"]
        for t in ("stated", "implied"):
            for k in (1, 2, 3):
                xs = [x for x in chains if x["claim_type"] == t and x["criticality"] == k]
                s1p0 = [x for x in s1 if x["claim_type"] == t and x["criticality"] == k and x["branch"] == "s1_p0"]
                own1 = boot(by_prompt(s1p0), lambda s: rate(s, "ownership", "owns"))
                surv = lambda after: (lambda s: sum(x["first"] is None or x["first"] > after for x in s) / len(s) if s else None)
                d2, d5 = boot(by_prompt(xs), surv(2)), boot(by_prompt(xs), surv(5))
                mf = boot(by_prompt(xs), lambda s: float(np.mean([x["first"] or 6 for x in s])) if s else None)
                R[f"crit_{t}_{k}"] = {"owns_s1": own1, "defends_after_s2": d2, "holds_s5": d5, "mean_first": mf,
                                      "n_prompts": len({x["prompt_id"] for x in xs})}
                md.append(f"| {t} | {k} | {len({x['prompt_id'] for x in xs})} | {fmt(own1)} | {fmt(d2)} | {fmt(d5)} | {fmt(mf, pct=False)} |")
        md.append(f"\nsilent+endorses replies (counted as Defends): {sum(bool(x['silent_endorse']) for x in it)}")
    (OUT / "summary.md").write_text("\n".join(md) + "\n")
    (OUT / "results.json").write_text(json.dumps(res, indent=1, default=str))
    if fig_data:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        fig, axes = plt.subplots(1, len(fig_data), figsize=(4.2 * len(fig_data), 3.2), sharey=True, squeeze=False)
        for ax, (m, surv) in zip(axes[0], fig_data.items()):
            for t, col in (("stated", "#3b6db3"), ("implied", "#c5481c")):
                if surv.get(t):
                    ax.step(range(0, 6), surv[t], where="post", label=t, color=col, lw=2)
            ax.set_xticks(range(0, 6), ["S0", "S1", "S2", "S3", "S4", "S5"])
            ax.set_title(m, fontsize=10)
            ax.set_ylim(0, 1.02)
            ax.grid(alpha=.3)
        axes[0][0].set_ylabel("share still Defending")
        axes[0][0].legend(frameon=False)
        fig.tight_layout()
        for ext in ("pdf", "png"):
            fig.savefig(OUT / f"survival.{ext}", dpi=200)
    print((OUT / "summary.md").read_text())


if __name__ == "__main__":
    main()
